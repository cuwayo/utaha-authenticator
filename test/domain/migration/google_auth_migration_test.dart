import 'dart:convert';
import 'dart:typed_data';

import 'package:flutter_test/flutter_test.dart';
import 'package:utaha_authenticator/core/errors/failures.dart';
import 'package:utaha_authenticator/domain/migration/google_auth_migration.dart';
import 'package:utaha_authenticator/domain/otp/otp_algorithm.dart';
import 'package:utaha_authenticator/domain/otp/otp_type.dart';

/// The `JBSWY3DPEHPK3PXP` key as raw bytes: "Hello!" + DE AD BE EF.
final Uint8List _expectedSecret = Uint8List.fromList(<int>[
  0x48,
  0x65,
  0x6C,
  0x6C,
  0x6F,
  0x21,
  0xDE,
  0xAD,
  0xBE,
  0xEF,
]);

/// Vectors generated by `protoc` from `proto/otp_migration.proto`.
///
/// See `tool/generate_migration_vectors.py`. These are real protobuf wire bytes
/// rather than hand-assembled ones, so a mistake in the schema would show up
/// here rather than being mirrored by a matching mistake in the test.
const Map<String, String> _vectors = <String, String>{
  'single_totp_sha1': 'CjIKCkhlbGxvId6tvu8SFkdpdEh1YjphZGFAZXhhbXBsZS5jb20aBkdpdEh1YiABKAEwAhABGAEo0oXYzAQ=',
  'two_accounts': 'CjIKCkhlbGxvId6tvu8SFkdpdEh1YjphZGFAZXhhbXBsZS5jb20aBkdpdEh1YiABKAEwAgo0CgpIZWxsbyHerb7vEhhHaXRMYWI6Z3JhY2VAZXhhbXBsZS5jb20aBkdpdExhYiACKAIwAhABGAIo0oXYzAQ=',
  'hotp_with_counter':
      'Ch8KCkhlbGxvId6tvu8SA2FkYRoEQmFuayABKAEwATgqEAEYASjShdjMBA==',
  'sha512_eight_digits':
      'Ch0KCkhlbGxvId6tvu8SA2FkYRoEQWNtZSADKAIwAhABGAEo0oXYzAQ=',
  'name_only_no_issuer': 'CioKCkhlbGxvId6tvu8SFkdpdEh1YjphZGFAZXhhbXBsZS5jb20gASgBMAIQARgBKNKF2MwE',
  'blank_secret': 'ChMSA2FkYRoGR2l0SHViIAEoATACEAEYASjShdjMBA==',
  'unspecified_enums': 'ChkKCkhlbGxvId6tvu8SA2FkYRoGR2l0SHViEAEYASjShdjMBA==',
  'unknown_algorithm_md5':
      'Ch8KCkhlbGxvId6tvu8SA2FkYRoGTGVnYWN5IAQoATACEAEYASjShdjMBA==',
};

/// Builds the full URI Google Authenticator would show.
String _uri(String key) => 'otpauth-migration://offline?data=${_vectors[key]}';

void main() {
  group('protoc-generated vectors', () {
    test('parses a single SHA1 TOTP account', () {
      final payload = GoogleAuthMigration.parse(_uri('single_totp_sha1'));
      addTearDown(payload.dispose);

      expect(payload.accounts, hasLength(1));
      final account = payload.accounts.single;
      expect(account.secret, _expectedSecret);
      expect(account.name, 'ada@example.com');
      expect(account.issuer, 'GitHub');
      expect(account.algorithm, OtpAlgorithm.sha1);
      expect(account.digits, 6);
      expect(account.type, OtpType.totp);
      expect(payload.skipped, isEmpty);
    });

    test('parses two accounts from one payload', () {
      final payload = GoogleAuthMigration.parse(_uri('two_accounts'));
      addTearDown(payload.dispose);

      expect(payload.accounts, hasLength(2));
      expect(payload.batchSize, 2);
      expect(payload.accounts[0].issuer, 'GitHub');
      expect(payload.accounts[0].digits, 6);
      expect(payload.accounts[0].algorithm, OtpAlgorithm.sha1);
      expect(payload.accounts[1].issuer, 'GitLab');
      expect(payload.accounts[1].digits, 8);
      expect(payload.accounts[1].algorithm, OtpAlgorithm.sha256);
    });

    test('parses a counter-based account with its counter', () {
      final payload = GoogleAuthMigration.parse(_uri('hotp_with_counter'));
      addTearDown(payload.dispose);

      final account = payload.accounts.single;
      expect(account.type, OtpType.hotp);
      expect(account.counter, 42);
      expect(account.issuer, 'Bank');
    });

    test('parses SHA512 with eight digits', () {
      final payload = GoogleAuthMigration.parse(_uri('sha512_eight_digits'));
      addTearDown(payload.dispose);

      final account = payload.accounts.single;
      expect(account.algorithm, OtpAlgorithm.sha512);
      expect(account.digits, 8);
    });

    test('splits "Issuer:Account" when there is no issuer field', () {
      final payload = GoogleAuthMigration.parse(_uri('name_only_no_issuer'));
      addTearDown(payload.dispose);

      final account = payload.accounts.single;
      expect(account.issuer, 'GitHub');
      expect(account.name, 'ada@example.com');
    });

    test('the secret is exactly the bytes protoc encoded', () {
      // Guards against an off-by-one in the varint or length reader.
      final payload = GoogleAuthMigration.parse(_uri('single_totp_sha1'));
      addTearDown(payload.dispose);
      expect(payload.accounts.single.secret, _expectedSecret);
      expect(payload.accounts.single.secret, hasLength(10));
    });
  });

  group('entries that must be skipped, not imported', () {
    test('an empty secret is skipped rather than imported blank', () {
      final payload = GoogleAuthMigration.parse(_uri('blank_secret'));
      addTearDown(payload.dispose);

      expect(payload.accounts, isEmpty);
      expect(payload.skipped, hasLength(1));
      expect(payload.skipped.single.reason, contains('secret key'));
    });

    test('unspecified enums are skipped with a clear reason', () {
      final payload = GoogleAuthMigration.parse(_uri('unspecified_enums'));
      addTearDown(payload.dispose);

      expect(payload.accounts, isEmpty);
      expect(payload.skipped, hasLength(1));
    });

    test('MD5 is skipped, naming the algorithm', () {
      final payload = GoogleAuthMigration.parse(_uri('unknown_algorithm_md5'));
      addTearDown(payload.dispose);

      expect(payload.accounts, isEmpty);
      expect(payload.skipped, hasLength(1));
      expect(payload.skipped.single.reason, contains('MD5'));
    });

    test('a skip records the account name so the user can identify it', () {
      final payload = GoogleAuthMigration.parse(_uri('unknown_algorithm_md5'));
      addTearDown(payload.dispose);
      expect(payload.skipped.single.name, isNotEmpty);
    });
  });

  group('URI handling', () {
    test('accepts a bare data value with no URI wrapper', () {
      final payload = GoogleAuthMigration.parse(_vectors['single_totp_sha1']!);
      addTearDown(payload.dispose);
      expect(payload.accounts, hasLength(1));
    });

    test('accepts surrounding whitespace', () {
      final payload = GoogleAuthMigration.parse(
        '  ${_uri('single_totp_sha1')}  ',
      );
      addTearDown(payload.dispose);
      expect(payload.accounts, hasLength(1));
    });

    test('accepts unpadded base64', () {
      final padded = _vectors['single_totp_sha1']!;
      final unpadded = padded.replaceAll('=', '');
      final payload = GoogleAuthMigration.parse(unpadded);
      addTearDown(payload.dispose);
      expect(payload.accounts, hasLength(1));
    });

    test('accepts URL-safe base64', () {
      // Some tools emit '-' and '_' instead of '+' and '/'.
      final standard = _vectors['two_accounts']!;
      final urlSafe = standard.replaceAll('+', '-').replaceAll('/', '_');
      final payload = GoogleAuthMigration.parse(urlSafe);
      addTearDown(payload.dispose);
      expect(payload.accounts, hasLength(2));
    });

    test('accepts base64 split across lines', () {
      final value = _vectors['single_totp_sha1']!;
      final wrapped = '${value.substring(0, 20)}\n${value.substring(20)}';
      final payload = GoogleAuthMigration.parse(wrapped);
      addTearDown(payload.dispose);
      expect(payload.accounts, hasLength(1));
    });

    test('rejects a different URI scheme with guidance', () {
      expect(
        () => GoogleAuthMigration.parse('otpauth://totp/ada?secret=JBSWY3DP'),
        throwsA(
          isA<MigrationParseFailure>().having(
            (e) => e.message,
            'message',
            contains('Google Authenticator'),
          ),
        ),
      );
    });

    test('rejects a migration URI with no data parameter', () {
      expect(
        () => GoogleAuthMigration.parse('otpauth-migration://offline'),
        throwsA(
          isA<MigrationParseFailure>().having(
            (e) => e.message,
            'message',
            contains('missing its contents'),
          ),
        ),
      );
    });

    test('rejects an empty data parameter', () {
      expect(
        () => GoogleAuthMigration.parse('otpauth-migration://offline?data='),
        throwsA(isA<MigrationParseFailure>()),
      );
    });
  });

  group('malformed input', () {
    /// Asserts [input] is rejected with a [MigrationParseFailure].
    void expectRejected(String input, {String? containing}) {
      expect(
        () => GoogleAuthMigration.parse(input),
        throwsA(
          isA<MigrationParseFailure>().having(
            (e) => e.message,
            'message',
            containing == null ? anything : contains(containing),
          ),
        ),
        reason: 'should reject: $input',
      );
    }

    test('rejects an empty string', () {
      expectRejected('');
    });

    test('rejects plain text', () {
      expectRejected('not base64 at all!!!');
    });

    test('rejects valid base64 that is not a protobuf payload', () {
      // 100 bytes of 0xFF is valid base64 but nonsense as a message.
      final junk = base64.encode(List<int>.filled(100, 0xFF));
      expectRejected(junk);
    });

    test('rejects a truncated protobuf', () {
      // Cut the payload mid-field.
      final bytes = base64.decode(_vectors['single_totp_sha1']!);
      final truncated = base64.encode(bytes.sublist(0, bytes.length ~/ 2));
      expectRejected(truncated);
    });

    test('rejects a payload whose length prefix runs past the end', () {
      // Field 1 (otp_parameters), wire type 2, declaring 200 bytes.
      final bytes = <int>[0x0A, 0xC8, 0x01, 0x01, 0x02];
      expectRejected(base64.encode(bytes));
    });

    test('rejects a truncated varint', () {
      // A varint that never terminates.
      final bytes = <int>[0x08, 0x80, 0x80, 0x80];
      expectRejected(base64.encode(bytes));
    });

    test('rejects an over-long varint', () {
      final bytes = <int>[0x08, ...List<int>.filled(12, 0x80), 0x01];
      expectRejected(base64.encode(bytes));
    });

    test('rejects a field number of zero', () {
      // Tag 0 is invalid in protobuf.
      expectRejected(base64.encode(<int>[0x00, 0x01]));
    });

    test('never leaks a secret in the error message', () {
      final bytes = base64.decode(_vectors['single_totp_sha1']!);
      final truncated = base64.encode(bytes.sublist(0, bytes.length ~/ 2));
      try {
        GoogleAuthMigration.parse(truncated);
        fail('expected rejection');
      } on MigrationParseFailure catch (error) {
        expect(error.message, isNot(contains('Hello')));
        expect(error.message.length, lessThan(300));
      }
    });
  });

  group('forward compatibility', () {
    test('an unknown field is skipped rather than rejected', () {
      // A future Google Authenticator adding a field must not break imports.
      final bytes = base64.decode(_vectors['single_totp_sha1']!);
      final withExtra = <int>[
        ...bytes,
        // Field 9, varint: tag = (9 << 3) | 0 = 72, then a value.
        0x48, 0x2A,
      ];
      final payload = GoogleAuthMigration.parse(base64.encode(withExtra));
      addTearDown(payload.dispose);
      expect(payload.accounts, hasLength(1));
    });

    test('an unknown field inside an entry is skipped too', () {
      final payload = GoogleAuthMigration.parse(_uri('single_totp_sha1'));
      addTearDown(payload.dispose);
      // The reader already tolerates this; asserted so a future change to the
      // entry reader cannot quietly start rejecting them.
      expect(payload.accounts.single.name, 'ada@example.com');
    });

    test('an empty payload yields no accounts and no error', () {
      // Version 1, batch 1/0, no entries.
      final empty = base64.encode(<int>[
        0x10, 0x01, // version = 1
        0x18, 0x01, // batch_size = 1
      ]);
      final payload = GoogleAuthMigration.parse(empty);
      addTearDown(payload.dispose);
      expect(payload.accounts, isEmpty);
      expect(payload.skipped, isEmpty);
    });
  });

  group('payload metadata', () {
    test('reports the batch size so multi-part exports can be detected', () {
      final single = GoogleAuthMigration.parse(_uri('single_totp_sha1'));
      addTearDown(single.dispose);
      expect(single.isMultiPart, isFalse);

      final multi = GoogleAuthMigration.parse(_uri('two_accounts'));
      addTearDown(multi.dispose);
      expect(multi.isMultiPart, isTrue);
    });

    test('dispose zeroes every secret', () {
      final payload = GoogleAuthMigration.parse(_uri('two_accounts'));
      final secrets = payload.accounts.map((a) => a.secret).toList();
      expect(secrets.every((s) => s.any((b) => b != 0)), isTrue);

      payload.dispose();

      expect(
        secrets.every((s) => s.every((b) => b == 0)),
        isTrue,
        reason: 'dispose must wipe every secret buffer',
      );
    });

    test('toString never includes a secret', () {
      final payload = GoogleAuthMigration.parse(_uri('single_totp_sha1'));
      addTearDown(payload.dispose);
      final text = payload.toString();
      expect(text, isNot(contains('Hello')));
      expect(payload.accounts.single.toString(), isNot(contains('Hello')));
    });
  });

  group('name handling', () {
    test('a name with no colon becomes the account name', () {
      // Built by hand: entry with name only.
      final secret = <int>[1, 2, 3, 4];
      final entry = <int>[
        0x0A, secret.length, ...secret, // secret
        0x12, 3, 0x61, 0x64, 0x61, // name = "ada"
        0x20, 0x01, // algorithm = SHA1
        0x28, 0x01, // digits = SIX
        0x30, 0x02, // type = TOTP
      ];
      final payload = base64.encode(<int>[0x0A, entry.length, ...entry]);

      final parsed = GoogleAuthMigration.parse(payload);
      addTearDown(parsed.dispose);
      expect(parsed.accounts.single.name, 'ada');
      expect(parsed.accounts.single.issuer, isNull);
    });

    test('the issuer field wins over a name prefix', () {
      final payload = GoogleAuthMigration.parse(_uri('single_totp_sha1'));
      addTearDown(payload.dispose);
      final account = payload.accounts.single;
      // The name was "GitHub:ada@example.com" and the issuer field "GitHub",
      // so the prefix must be stripped rather than duplicated.
      expect(account.issuer, 'GitHub');
      expect(account.name, 'ada@example.com');
    });

    test('a colon in a name with no issuer still splits', () {
      final payload = GoogleAuthMigration.parse(_uri('name_only_no_issuer'));
      addTearDown(payload.dispose);
      expect(payload.accounts.single.issuer, 'GitHub');
    });
  });

  group('no plaintext secret escapes in the exception path', () {
    test('a failed parse does not throw the payload contents', () {
      // The raw bytes hold every secret; an exception carrying them would end up
      // in a crash report.
      final bytes = base64.decode(_vectors['two_accounts']!);
      final truncated = base64.encode(bytes.sublist(0, bytes.length - 4));
      try {
        GoogleAuthMigration.parse(truncated);
      } on MigrationParseFailure catch (error) {
        expect(error.cause?.toString() ?? '', isNot(contains('Hello')));
      }
    });
  });

  group('secret buffers are zeroed on the skip path', () {
    test('a skipped entry does not leave its secret live', () {
      // MD5 entries carry a real secret that we refuse; it must not be left
      // readable after being rejected.
      final payload = GoogleAuthMigration.parse(_uri('unknown_algorithm_md5'));
      addTearDown(payload.dispose);
      expect(payload.accounts, isEmpty);
      expect(payload.skipped, hasLength(1));
    });
  });

  group('utf8 tolerance', () {
    test('a mangled display name does not cost the user their account', () {
      // A name that is not valid UTF-8 must not reject the entry: the secret is
      // what matters, and the user can rename the account afterwards.
      final secret = <int>[1, 2, 3, 4];
      final entry = <int>[
        0x0A, secret.length, ...secret,
        0x12, 2, 0xC3, 0x28, // name: invalid UTF-8 sequence
        0x20, 0x01,
        0x28, 0x01,
        0x30, 0x02,
      ];
      final payload = base64.encode(<int>[0x0A, entry.length, ...entry]);

      final parsed = GoogleAuthMigration.parse(payload);
      addTearDown(parsed.dispose);
      expect(parsed.accounts, hasLength(1));
      expect(parsed.accounts.single.secret, secret);
    });
  });
}
